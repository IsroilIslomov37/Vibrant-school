export const LANG_KEY = 'vibrant.lang'
export const LangContext = createContext(null)

let LANG = 'ru'
try {
  const saved = localStorage.getItem(LANG_KEY)
  if (saved && LANGS.some((l) => l.id === saved)) LANG = saved
} catch {
  /* localStorage недоступен */
}

export const getLang = () => LANG
export function applyLang(lang) {
  LANG = lang
  try {
    localStorage.setItem(LANG_KEY, lang)
    document.documentElement.lang = lang
  } catch {
    /* ignore */
  }
}
applyLang(LANG)

export function useLang() {
  const ctx = useContext(LangContext)
  if (!ctx) throw new Error('useLang должен использоваться внутри LangProvider')
  return ctx
}

/** t('login.title') · t('common.ofTotal', { n: 5 }) */
export function t(key, vars) {
  const raw = lookup(DICT[LANG], key) ?? lookup(DICT.ru, key) ?? key
  if (!vars) return raw
  return String(raw).replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m))
}

function lookup(dict, key) {
  return key.split('.').reduce((acc, part) => (acc == null ? acc : acc[part]), dict)
}

