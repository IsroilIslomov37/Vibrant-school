export function fmtDate(d) {
  if (!d) return '—'
  const [year, month, day] = String(d).slice(0, 10).split('-').map(Number)
  if (!year || !month || !day) return '—'
  const name = MONTHS[LANG][month - 1]
  return LANG === 'uz' ? day + '-' + name + ' ' + year : day + ' ' + name + ' ' + year
}

